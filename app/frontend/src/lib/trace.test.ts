import { describe, expect, it } from 'vitest'
import { hopText, traceSummary } from './trace'
import type { TraceView } from './types'

const base: TraceView = { name: 'vars.token', kind: 'variable', producers: ['session'], readers: ['verify', 'show'], generated: false, lit: ['session', 'verify', 'show'], hops: [] }

describe('traceSummary', () => {
  it('names the makers and the readers', () => {
    expect(traceSummary(base)).toBe('made by session · read by verify, show')
  })
  it('says a generated value is fresh', () => {
    expect(traceSummary({ ...base, generated: true })).toBe('generated by session · read by verify, show')
  })
  it('says an input comes from outside the flow', () => {
    expect(traceSummary({ ...base, name: 'inputs.region', kind: 'input', producers: [] })).toBe('a flow input · read by verify, show')
  })
  it('says when nothing makes or reads it', () => {
    expect(traceSummary({ ...base, producers: [], readers: [] })).toBe('nothing makes it · no step reads it')
  })
})

describe('hopText', () => {
  it('says what a step made and what a step read', () => {
    expect(hopText({ node: 'session', role: 'made', value: 't-1', known: true })).toBe('session made t-1')
    expect(hopText({ node: 'verify', role: 'read', value: 't-1', known: true })).toBe('verify read t-1')
  })
  it('says when the run has no value for the hop', () => {
    expect(hopText({ node: 'late', role: 'read', value: '', known: false })).toBe('late read (no value)')
  })
})
