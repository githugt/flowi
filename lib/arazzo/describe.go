// SchemaLookup gives Describe the schemas learned (or imported) for a request
// version: the body it sends and the body of each response status. Either may
// be absent; a nil lookup describes bodies loosely.
type SchemaLookup interface {
	RequestSchema(r model.Request, version string) (map[string]any, bool)
	ResponseSchemas(r model.Request, version string) map[int]map[string]any
}

// Describe writes the OpenAPI description of a collection's requests: one
// operation per request version, so an Arazzo step can name a hand-made
// request by operationId. It is derived (rewritten whenever the requests or
// their schemas change) and never edited. It carries parameter names, never
// values, and always declares the built-in operation custom steps call.
func Describe(c model.Collection, schemas SchemaLookup) ([]byte, error) {
	ops := operationsOf(c)
	servers := serversOf(ops)
	doc := yaml.MapSlice{
		{Key: "openapi", Value: "3.1.0"},
		{Key: "info", Value: yaml.MapSlice{
			{Key: "title", Value: cmp.Or(c.Manifest.Name, "Collection")},
			{Key: "version", Value: "1.0.0"},
			{Key: "description", Value: "Generated by Flowi from the requests of this collection. Do not edit: it is rewritten when they change."},
		}},
	}
	if len(servers) > 0 {
		doc = append(doc, yaml.MapItem{Key: "servers", Value: servers})
	}
	doc = append(doc, yaml.MapItem{Key: "paths", Value: pathsOf(ops, schemas)})
	out, err := yaml.MarshalWithOptions(doc, yaml.IndentSequence(true))
	if err != nil {
		return nil, fmt.Errorf("writing the description: %w", err)
	}
	return out, nil
}

// operation is one request version as an OpenAPI operation.
type operation struct {
	req       model.Request
	version   model.RequestVersion
	id        string
	method    string
	path      string
	server    string // a server variable name, or "" (an absolute URL's host is in host)
	host      string
	query     []string
	headers   []string
	pathNames []string
}

var (
	envPrefix  = regexp.MustCompile(`^\{\{\s*env\.([A-Za-z0-9_]+)\s*\}\}`)
	templateRe = regexp.MustCompile(`\{\{\s*([^}]*?)\s*\}\}`)
	lastName   = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*$`)
	notIDRune  = regexp.MustCompile(`[^A-Za-z0-9_]`)
)

// operationsOf lists every request version as an operation, with ids that are
// stable: assigned in path order, a clash gets _2, _3, … so adding a request
// after the others never renames theirs.
func operationsOf(c model.Collection) []operation {
	reqs := slices.Clone(c.Requests)
	slices.SortFunc(reqs, func(a, b model.Request) int { return strings.Compare(a.Path, b.Path) })
	taken := map[string]bool{}
	var out []operation
	for _, r := range reqs {
		def := defaultLabel(r)
		for _, v := range r.Versions {
			if v.Async != nil {
				continue // described by DescribeAsync
			}
			if customKind(v) != "" {
				continue // no standard description of a gRPC call or a dataset query is generated
			}
			base := slug(r.Path)
			switch {
			case v.Label == def && r.Operation != "":
				base = r.Operation
			case v.Label != def:
				base += "_v" + slug(v.Label)
			}
			id := base
			for n := 2; taken[id] || id == BuiltinOperation; n++ {
				id = base + "_" + strconv.Itoa(n)
			}
			taken[id] = true
			out = append(out, newOperation(r, v, id))
		}
	}
	return out
}

func defaultLabel(r model.Request) string {
	if r.Default != "" {
		return r.Default
	}
	if len(r.Versions) > 0 {
		return r.Versions[0].Label
	}
	return ""
}

func slug(s string) string {
	out := strings.Trim(notIDRune.ReplaceAllString(s, "_"), "_")
	return cmp.Or(out, "request")
}

func newOperation(r model.Request, v model.RequestVersion, id string) operation {
	op := operation{req: r, version: v, id: id, method: cmp.Or(v.Method, "GET")}
	rest := v.URL
	if m := envPrefix.FindStringSubmatch(rest); m != nil {
		op.server = m[1]
		rest = rest[len(m[0]):]
	} else if i := strings.Index(rest, "://"); i > 0 {
		afterHost := strings.Index(rest[i+3:], "/")
		if afterHost < 0 {
			op.host, rest = rest, ""
		} else {
			op.host, rest = rest[:i+3+afterHost], rest[i+3+afterHost:]
		}
	}
	pathPart, queryPart, _ := strings.Cut(rest, "?")
	op.path = pathTemplate(pathPart, &op.pathNames)
	for _, pair := range strings.Split(queryPart, "&") {
		if name, _, _ := strings.Cut(pair, "="); name != "" && !strings.Contains(name, "{{") {
			op.query = appendUnique(op.query, name)
		}
	}
	for _, kv := range v.Query {
		op.query = appendUnique(op.query, kv.Key)
	}
	for _, kv := range v.Headers {
		if k := strings.ToLower(kv.Key); k != "content-type" && k != "accept" {
			op.headers = appendUnique(op.headers, kv.Key)
		}
	}
	return op
}

func appendUnique(list []string, s string) []string {
	if s == "" || slices.Contains(list, s) {
		return list
	}
	return append(list, s)
}

// pathTemplate turns {{id}} segments into {id} path parameters, collecting their names.
func pathTemplate(p string, names *[]string) string {
	out := templateRe.ReplaceAllStringFunc(p, func(m string) string {
		inner := templateRe.FindStringSubmatch(m)[1]
		name := lastName.FindString(inner)
		if name == "" {
			name = "param"
		}
		*names = appendUnique(*names, name)
		return "{" + name + "}"
	})
	if !strings.HasPrefix(out, "/") {
		out = "/" + out
	}
	return out
}

func serversOf(ops []operation) []any {
	seenVars, seenHosts := map[string]bool{}, map[string]bool{}
	var out []any
	for _, op := range ops {
		switch {
		case op.server != "" && !seenVars[op.server]:
			seenVars[op.server] = true
			out = append(out, yaml.MapSlice{
				{Key: "url", Value: "{" + op.server + "}"},
				{Key: "variables", Value: yaml.MapSlice{{Key: op.server, Value: yaml.MapSlice{{Key: "default", Value: "http://localhost"}}}}},
			})
		case op.host != "" && !seenHosts[op.host]:
			seenHosts[op.host] = true
			out = append(out, yaml.MapSlice{{Key: "url", Value: op.host}})
		}
	}
	return out
}

// methodOrder are the methods an OpenAPI path item has a field for, in the order they are written; QUERY is 3.2's.
var methodOrder = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace", "query"} //nolint:gochecknoglobals // a fixed ordering table

// fieldOf is the key a method has in a path item: its lower-case field, or "" for a method that has none (WebDAV's
// PROPFIND, a CDN's Purge), which OpenAPI 3.2 keeps in additionalOperations under its own, case-sensitive, name.
func fieldOf(method string) string {
	if lower := strings.ToLower(method); slices.Contains(methodOrder, lower) {
		return lower
	}
	return ""
}

func pathsOf(ops []operation, schemas SchemaLookup) yaml.MapSlice {
	byPath := map[string]map[string]any{}
	var order []string
	add := func(path, method string, body yaml.MapSlice) {
		if field := fieldOf(method); field != "" {
			method = field
		}
		if _, taken := byPath[path][method]; taken {
			path += "?flowi=" + method + strconv.Itoa(len(order)) // two requests on one URL and method: keep both
		}
		if byPath[path] == nil {
			byPath[path] = map[string]any{}
			order = append(order, path)
		}
		byPath[path][method] = body
	}
	for _, op := range ops {
		add(op.path, op.method, operationYAML(op, schemas))
	}
	add("/flowi/custom", "post", yaml.MapSlice{
		{Key: "operationId", Value: BuiltinOperation},
		{Key: "summary", Value: "Flowi custom step"},
		{Key: "description", Value: "A step only Flowi can run. The node it stands for is in the flow's x-flowi-flow. Other tools cannot call it."},
		{Key: "responses", Value: yaml.MapSlice{{Key: "default", Value: yaml.MapSlice{{Key: "description", Value: "Not callable outside Flowi"}}}}},
	})
	slices.Sort(order)
	var out yaml.MapSlice
	for _, p := range order {
		var item yaml.MapSlice
		for _, m := range methodOrder {
			if body, ok := byPath[p][m]; ok {
				item = append(item, yaml.MapItem{Key: m, Value: body})
			}
		}
		if extra := additionalOperationsOf(byPath[p]); extra != nil {
			item = append(item, yaml.MapItem{Key: "additionalOperations", Value: extra})
		}
		out = append(out, yaml.MapItem{Key: p, Value: item})
	}
	return out
}

// additionalOperationsOf are the operations of a path item whose method has no field of its own, by name; nil for none.
func additionalOperationsOf(ops map[string]any) yaml.MapSlice {
	var out yaml.MapSlice
	for _, name := range slices.Sorted(maps.Keys(ops)) {
		if !slices.Contains(methodOrder, name) {
			out = append(out, yaml.MapItem{Key: name, Value: ops[name]})
		}
	}
	return out
}

func operationYAML(op operation, schemas SchemaLookup) yaml.MapSlice {
	out := yaml.MapSlice{{Key: "operationId", Value: op.id}}
	if name := cmp.Or(op.req.Name, op.req.Path); name != "" {
		out = append(out, yaml.MapItem{Key: "summary", Value: name})
	}
	out = append(out, yaml.MapItem{Key: "x-flowi-request", Value: string(op.req.ID)})
	if params := parametersOf(op); len(params) > 0 {
		out = append(out, yaml.MapItem{Key: "parameters", Value: params})
	}
	if body := requestBodyOf(op, schemas); body != nil {
		out = append(out, yaml.MapItem{Key: "requestBody", Value: body})
	}
	return append(out, yaml.MapItem{Key: "responses", Value: responsesOf(op, schemas)})
}

func parametersOf(op operation) []any {
	var out []any
	param := func(name, in string, required bool) {
		p := yaml.MapSlice{{Key: "name", Value: name}, {Key: "in", Value: in}}
		if required {
			p = append(p, yaml.MapItem{Key: "required", Value: true})
		}
		out = append(out, append(p, yaml.MapItem{Key: "schema", Value: yaml.MapSlice{{Key: "type", Value: "string"}}}))
	}
	for _, n := range op.pathNames {
		param(n, "path", true)
	}
	for _, n := range op.query {
		param(n, "query", false)
	}
	for _, n := range op.headers {
		param(n, "header", false)
	}
	return out
}

func requestBodyOf(op operation, schemas SchemaLookup) any {
	b := op.version.Body
	media, schema := "", any(yaml.MapSlice{})
	switch {
	case b.JSON != "":
		media = "application/json"
		if schemas != nil {
			if s, ok := schemas.RequestSchema(op.req, op.version.Label); ok {
				schema = s
			}
		}
	case len(b.Form) > 0:
		media, schema = "application/x-www-form-urlencoded", formSchema(b.Form)
	case len(b.Multipart) > 0:
		media = "multipart/form-data"
	case b.File != "":
		media = "application/octet-stream"
	case b.Text != "":
		media, schema = "text/plain", yaml.MapSlice{{Key: "type", Value: "string"}}
	default:
		return nil
	}
	return yaml.MapSlice{{Key: "content", Value: yaml.MapSlice{{Key: media, Value: yaml.MapSlice{{Key: "schema", Value: schema}}}}}}
}

func formSchema(fields []model.KeyValue) yaml.MapSlice {
	var props yaml.MapSlice
	for _, f := range fields {
		props = append(props, yaml.MapItem{Key: f.Key, Value: yaml.MapSlice{{Key: "type", Value: "string"}}})
	}
	return yaml.MapSlice{{Key: "type", Value: "object"}, {Key: "properties", Value: props}}
}

func responsesOf(op operation, schemas SchemaLookup) yaml.MapSlice {
	var out yaml.MapSlice
	if schemas != nil {
		byStatus := schemas.ResponseSchemas(op.req, op.version.Label)
		statuses := make([]int, 0, len(byStatus))
		for s := range byStatus {
			statuses = append(statuses, s)
		}
		slices.Sort(statuses)
		for _, s := range statuses {
			out = append(out, yaml.MapItem{Key: strconv.Itoa(s), Value: yaml.MapSlice{
				{Key: "description", Value: "Status " + strconv.Itoa(s)},
				{Key: "content", Value: yaml.MapSlice{{Key: "application/json", Value: yaml.MapSlice{{Key: "schema", Value: byStatus[s]}}}}},
			}})
		}
	}
	if len(out) == 0 {
		out = yaml.MapSlice{{Key: "default", Value: yaml.MapSlice{{Key: "description", Value: "Response"}}}}
	}
	return out
}

// NewResolver resolves the operations Describe declares: the operation a
// request call runs, and the request behind an operationId.
func NewResolver(c model.Collection) Resolver {
	return describedResolver{ops: operationsOf(c), async: asyncOperationsOf(c), custom: customRequestsOf(c)}
}

type describedResolver struct {
	ops    []operation
	async  []asyncOperation
	custom []model.Request // requests with a gRPC or dataset version (they have no described operation)
}

// customKind is what a version is called in a limit when it has no standard description: "" for one that has.
func customKind(v model.RequestVersion) string {
	switch v.Family() {
	case model.FamilyRPC:
		return "gRPC call"
	case model.FamilyDataset:
		return "dataset query"
	}
	return ""
}

// customRequestsOf lists the requests that have a gRPC or a dataset version.
func customRequestsOf(c model.Collection) []model.Request {
	var out []model.Request
	for _, r := range c.Requests {
		if slices.ContainsFunc(r.Versions, func(v model.RequestVersion) bool { return customKind(v) != "" }) {
			out = append(out, r)
		}
	}
	return out
}

// customKindOf is what the version call runs is called when it has no standard description, "" when it has one.
func (r describedResolver) customKindOf(call model.RequestCall) string {
	for _, req := range r.custom {
		if !sameRequest(req, call.Request) {
			continue
		}
		want := cmp.Or(call.Version, defaultLabel(req))
		for _, v := range req.Versions {
			if v.Label == want {
				return customKind(v)
			}
		}
	}
	return ""
}

func (r describedResolver) RequestFor(operationID string) (model.Ref, string, bool) {
	for _, op := range r.ops {
		if op.id == operationID {
			version := op.version.Label
			if version == defaultLabel(op.req) {
				version = ""
			}
			return model.Ref{ID: op.req.ID, Path: op.req.Path}, version, true
		}
	}
	for _, op := range r.async {
		if op.id == operationID {
			version := op.version.Label
			if version == defaultLabel(op.req) {
				version = ""
			}
			return model.Ref{ID: op.req.ID, Path: op.req.Path}, version, true
		}
	}
	return model.Ref{}, "", false
}

func (r describedResolver) OperationOf(call model.RequestCall) (Operation, bool) {
	if kind := r.customKindOf(call); kind != "" {
		return Operation{Custom: kind}, true
	}
	for _, op := range r.async {
		if sameRequest(op.req, call.Request) && op.version.Label == cmp.Or(call.Version, defaultLabel(op.req)) {
			return op.operation(), true
		}
	}
	for _, op := range r.ops {
		if !sameRequest(op.req, call.Request) {
			continue
		}
		want := cmp.Or(call.Version, defaultLabel(op.req))
		if op.version.Label != want {
			continue
		}
		params := map[string]Param{}
		for _, n := range op.pathNames {
			params[openapi.ParamKey(n)] = Param{Name: n, In: "path"}
		}
		for _, n := range op.query {
			params[openapi.ParamKey(n)] = Param{Name: n, In: "query"}
		}
		for _, n := range op.headers {
			params[openapi.ParamKey(n)] = Param{Name: n, In: "header"}
		}
		return Operation{ID: op.id, Params: params}, true
	}
	return Operation{}, false
}

func sameRequest(r model.Request, ref model.Ref) bool {
	return (ref.ID != "" && ref.ID == r.ID) || (ref.ID == "" && ref.Path != "" && ref.Path == r.Path)
}
