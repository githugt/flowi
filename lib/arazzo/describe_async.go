// AsyncSchemaLookup gives DescribeAsync the schemas learned for an async
// request version: the payload it sends and the payload of the messages it
// receives. Either may be absent; a nil lookup describes payloads loosely.
type AsyncSchemaLookup interface {
	RequestSchema(r model.Request, version string) (map[string]any, bool)
	MessageSchema(r model.Request, version string) (map[string]any, bool)
}

// DescribeAsync writes the AsyncAPI 3.0 description of a collection's async
// requests: one operation per async request version, so an Arazzo step can
// name one by operationId. Like Describe it is derived and never edited, and
// carries no credentials. It returns nil when the collection has no async
// request.
func DescribeAsync(c model.Collection, schemas AsyncSchemaLookup) ([]byte, error) {
	ops := asyncOperationsOf(c)
	if len(ops) == 0 {
		return nil, nil
	}
	doc := yaml.MapSlice{
		{Key: "asyncapi", Value: "3.0.0"},
		{Key: "info", Value: yaml.MapSlice{
			{Key: "title", Value: cmp.Or(c.Manifest.Name, "Collection")},
			{Key: "version", Value: "1.0.0"},
			{Key: "description", Value: "Generated by Flowi from the async requests of this collection. Do not edit: it is rewritten when they change."},
		}},
		{Key: "servers", Value: asyncServers(ops)},
		{Key: "channels", Value: asyncChannels(ops, schemas)},
		{Key: "operations", Value: asyncOperationsYAML(ops)},
	}
	out, err := yaml.MarshalWithOptions(doc, yaml.IndentSequence(true))
	if err != nil {
		return nil, fmt.Errorf("writing the async description: %w", err)
	}
	return out, nil
}

// asyncOperation is one async request version as an AsyncAPI operation.
type asyncOperation struct {
	req       model.Request
	version   model.RequestVersion
	async     model.Async
	id        string
	channelID string
	address   string
	params    []string
	server    asyncServer
}

type asyncServer struct {
	name, host, pathname, protocol string
	extension                      string // x-flowi-protocol, for a service AsyncAPI has no protocol name for
	variable                       string // the env variable a templated server comes from
}

// asyncOperationsOf lists every async version as an operation, with ids that
// are stable: assigned in path order, a clash gets _2, _3, …
func asyncOperationsOf(c model.Collection) []asyncOperation {
	reqs := slices.Clone(c.Requests)
	slices.SortFunc(reqs, func(a, b model.Request) int { return strings.Compare(a.Path, b.Path) })
	taken := map[string]bool{}
	var out []asyncOperation
	for _, r := range reqs {
		def := defaultLabel(r)
		for _, v := range r.Versions {
			if v.Async == nil {
				continue
			}
			base := slug(r.Path)
			switch {
			case v.Label == def && r.Operation != "":
				base = r.Operation
			case v.Label != def:
				base += "_v" + slug(v.Label)
			}
			id := base
			for n := 2; taken[id]; n++ {
				id = fmt.Sprintf("%s_%d", base, n)
			}
			taken[id] = true
			out = append(out, newAsyncOperation(r, v, id))
		}
	}
	return out
}

func newAsyncOperation(r model.Request, v model.RequestVersion, id string) asyncOperation {
	op := asyncOperation{req: r, version: v, async: *v.Async, id: id}
	op.address = pathTemplate0(v.Async.Channel, &op.params)
	op.channelID = slug(strings.NewReplacer("{", "", "}", "").Replace(op.address))
	op.server = serverOf(*v.Async)
	return op
}

// pathTemplate0 turns {{x}} in a channel address into {x} parameters (no
// leading slash is added, unlike an HTTP path).
func pathTemplate0(address string, names *[]string) string {
	return templateRe.ReplaceAllStringFunc(address, func(m string) string {
		name := lastName.FindString(templateRe.FindStringSubmatch(m)[1])
		if name == "" {
			name = "param"
		}
		*names = appendUnique(*names, name)
		return "{" + name + "}"
	})
}

// serverOf describes where an async version connects. A server that starts
// with {{env.x}} becomes a server variable named x.
func serverOf(a model.Async) asyncServer {
	proto, ext := documentProtocol(a.Protocol)
	if m := envPrefix.FindStringSubmatch(a.Server); m != nil {
		return asyncServer{name: m[1], host: "{" + m[1] + "}", protocol: cmp.Or(proto, a.Protocol), extension: ext, variable: m[1]}
	}
	if proto != "" {
		return managedServer(a, proto, ext)
	}
	u, err := url.Parse(a.Server)
	if err != nil || u.Host == "" && !strings.Contains(a.Server, "://") {
		return asyncServer{name: "default", host: "localhost", protocol: a.Protocol}
	}
	scheme, rest, _ := strings.Cut(a.Server, "://")
	hosts, path, _ := strings.Cut(rest, "/")
	s := asyncServer{host: withoutUserInfo(hosts), protocol: protocolName(strings.ToLower(scheme), a.Protocol), extension: ext}
	if path != "" {
		s.pathname = "/" + path
	}
	s.name = slug(s.protocol + "_" + s.host)
	return s
}

// documentProtocol is the AsyncAPI protocol name of Redis and the managed
// services, and the x-flowi-protocol extension for Service Bus (written as
// amqps, which is what it speaks). Open protocols return "" and are named by
// the scheme of their server.
func documentProtocol(protocol string) (name, extension string) {
	switch protocol {
	case model.ProtocolRedis:
		return "redis", ""
	case model.ProtocolSQS:
		return "sqs", ""
	case model.ProtocolSNS:
		return "sns", ""
	case model.ProtocolPubSub:
		return "googlepubsub", ""
	case model.ProtocolServiceBus:
		return "amqps", model.ProtocolServiceBus
	case model.ProtocolAMQP10:
		return "", model.ProtocolAMQP10 // named by its scheme, like AMQP 0-9-1, and told apart by the extension
	}
	return "", ""
}

// managedServer describes the server of Redis or a managed service: the host
// (or project, or namespace) without scheme or credentials. SQS and SNS with
// no server reach AWS itself.
func managedServer(a model.Async, proto, ext string) asyncServer {
	_, rest, found := strings.Cut(a.Server, "://")
	if !found {
		rest = a.Server
	}
	host, path, _ := strings.Cut(rest, "/")
	host = withoutUserInfo(host)
	if host == "" {
		host = awsHost(a.Protocol)
	}
	s := asyncServer{host: host, protocol: proto, extension: ext}
	if path != "" {
		s.pathname = "/" + path
	}
	s.name = slug(cmp.Or(ext, proto) + "_" + host)
	return s
}

func awsHost(protocol string) string {
	if protocol == model.ProtocolSQS || protocol == model.ProtocolSNS {
		return protocol + ".amazonaws.com"
	}
	return "localhost"
}

// withoutUserInfo drops user:password@ from each host of a comma-separated
// list; the description never carries credentials.
func withoutUserInfo(hosts string) string {
	parts := strings.Split(hosts, ",")
	for i, p := range parts {
		parts[i] = p[strings.LastIndex(p, "@")+1:]
	}
	return strings.Join(parts, ",")
}

// protocolName maps a URL scheme to the protocol name AsyncAPI documents use.
func protocolName(scheme, fallback string) string {
	switch scheme {
	case "kafkas":
		return "kafka-secure"
	case "mqtts":
		return "secure-mqtt"
	case "":
		return fallback
	}
	return scheme
}

func asyncServers(ops []asyncOperation) yaml.MapSlice {
	byName := map[string]asyncServer{}
	for _, op := range ops {
		byName[op.server.name] = op.server
	}
	names := sortedKeys(byName)
	var out yaml.MapSlice
	for _, n := range names {
		s := byName[n]
		item := yaml.MapSlice{{Key: "host", Value: s.host}, {Key: "protocol", Value: s.protocol}}
		if s.extension != "" {
			item = append(item, yaml.MapItem{Key: "x-flowi-protocol", Value: s.extension})
		}
		if s.pathname != "" {
			item = append(item, yaml.MapItem{Key: "pathname", Value: s.pathname})
		}
		if s.variable != "" {
			item = append(item, yaml.MapItem{Key: "variables", Value: yaml.MapSlice{
				{Key: s.variable, Value: yaml.MapSlice{{Key: "default", Value: "localhost"}}}}})
		}
		out = append(out, yaml.MapItem{Key: n, Value: item})
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

func asyncChannels(ops []asyncOperation, schemas AsyncSchemaLookup) yaml.MapSlice {
	type channel struct {
		address  string
		params   []string
		server   string
		messages map[string]yaml.MapSlice
	}
	byID := map[string]*channel{}
	for _, op := range ops {
		ch := byID[op.channelID]
		if ch == nil {
			ch = &channel{address: op.address, params: op.params, server: op.server.name, messages: map[string]yaml.MapSlice{}}
			byID[op.channelID] = ch
		}
		for id, msg := range asyncMessages(op, schemas) {
			ch.messages[id] = msg
		}
	}
	var out yaml.MapSlice
	for _, id := range sortedKeys(byID) {
		ch := byID[id]
		item := yaml.MapSlice{{Key: "address", Value: ch.address}}
		var msgs yaml.MapSlice
		for _, m := range sortedKeys(ch.messages) {
			msgs = append(msgs, yaml.MapItem{Key: m, Value: ch.messages[m]})
		}
		item = append(item, yaml.MapItem{Key: "messages", Value: msgs})
		if len(ch.params) > 0 {
			var params yaml.MapSlice
			for _, p := range ch.params {
				params = append(params, yaml.MapItem{Key: p, Value: yaml.MapSlice{}})
			}
			item = append(item, yaml.MapItem{Key: "parameters", Value: params})
		}
		item = append(item, yaml.MapItem{Key: "servers", Value: []any{yaml.MapSlice{{Key: "$ref", Value: "#/servers/" + ch.server}}}})
		out = append(out, yaml.MapItem{Key: id, Value: item})
	}
	return out
}

// asyncMessages are the messages an operation sends and receives, by id.
func asyncMessages(op asyncOperation, schemas AsyncSchemaLookup) map[string]yaml.MapSlice {
	out := map[string]yaml.MapSlice{}
	payload := func(loaded map[string]any, ok bool) yaml.MapSlice {
		msg := yaml.MapSlice{{Key: "name", Value: op.id}}
		if ok {
			msg = append(msg, yaml.MapItem{Key: "payload", Value: loaded})
		}
		return msg
	}
	if schemas == nil {
		schemas = noAsyncSchemas{}
	}
	if op.async.Send != nil {
		s, ok := schemas.RequestSchema(op.req, op.version.Label)
		out[op.id] = payload(s, ok)
	}
	if op.async.Receive != nil {
		s, ok := schemas.MessageSchema(op.req, op.version.Label)
		key := op.id
		if op.async.Send != nil {
			key = op.id + "_reply"
		}
		out[key] = payload(s, ok)
	}
	return out
}

type noAsyncSchemas struct{}

func (noAsyncSchemas) RequestSchema(model.Request, string) (map[string]any, bool) { return nil, false }
func (noAsyncSchemas) MessageSchema(model.Request, string) (map[string]any, bool) { return nil, false }

func asyncOperationsYAML(ops []asyncOperation) yaml.MapSlice {
	sorted := slices.Clone(ops)
	slices.SortFunc(sorted, func(a, b asyncOperation) int { return strings.Compare(a.id, b.id) })
	var out yaml.MapSlice
	for _, op := range sorted {
		out = append(out, yaml.MapItem{Key: op.id, Value: asyncOperationYAML(op)})
	}
	return out
}

func asyncOperationYAML(op asyncOperation) yaml.MapSlice {
	ref := func(msg string) []any {
		return []any{yaml.MapSlice{{Key: "$ref", Value: "#/channels/" + op.channelID + "/messages/" + msg}}}
	}
	channel := yaml.MapSlice{{Key: "$ref", Value: "#/channels/" + op.channelID}}
	out := yaml.MapSlice{{Key: "action", Value: asyncAction(op.async)}, {Key: "channel", Value: channel}}
	if name := cmp.Or(op.req.Name, op.req.Path); name != "" {
		out = append(out, yaml.MapItem{Key: "summary", Value: name})
	}
	switch op.async.Action() {
	case model.AsyncSendOnly:
		out = append(out, yaml.MapItem{Key: "messages", Value: ref(op.id)})
	case model.AsyncReceiveOnly:
		out = append(out, yaml.MapItem{Key: "messages", Value: ref(op.id)})
	case model.AsyncRequestReply:
		out = append(out, yaml.MapItem{Key: "messages", Value: ref(op.id)},
			yaml.MapItem{Key: "reply", Value: yaml.MapSlice{{Key: "channel", Value: channel}, {Key: "messages", Value: ref(op.id + "_reply")}}})
	}
	if b := mqttBinding(op.async); b != nil {
		out = append(out, yaml.MapItem{Key: "bindings", Value: yaml.MapSlice{{Key: "mqtt", Value: b}}})
	}
	out = append(out, yaml.MapItem{Key: "x-flowi-request", Value: string(op.req.ID)})
	if kv := publicBinding(op.async.Binding); len(kv) > 0 {
		out = append(out, yaml.MapItem{Key: "x-flowi-binding", Value: kv})
	}
	return out
}

// asyncAction is the AsyncAPI action: a request and reply sends and then
// receives, which AsyncAPI writes as a send with a reply.
func asyncAction(a model.Async) string {
	if a.Action() == model.AsyncReceiveOnly {
		return "receive"
	}
	return "send"
}

func mqttBinding(a model.Async) yaml.MapSlice {
	if a.Protocol != model.ProtocolMQTT {
		return nil
	}
	var out yaml.MapSlice
	for _, kv := range a.Binding {
		switch kv.Key {
		case "qos":
			out = append(out, yaml.MapItem{Key: "qos", Value: atoiOr(kv.Value, 0)})
		case "retain":
			out = append(out, yaml.MapItem{Key: "retain", Value: kv.Value == "true"})
		}
	}
	if out == nil {
		return nil
	}
	return append(out, yaml.MapItem{Key: "bindingVersion", Value: "0.2.0"})
}

func atoiOr(s string, def int) int {
	var n int
	if _, err := fmt.Sscanf(s, "%d", &n); err != nil {
		return def
	}
	return n
}

// secretBindingName reports whether a binding holds a credential; those are
// never written to the description.
func secretBindingName(name string) bool {
	for _, p := range model.AsyncProtocols() {
		if slices.Contains(model.AsyncCredentials(p), name) {
			return true
		}
	}
	return false
}

// publicBinding keeps the binding options that are safe to publish: not
// credentials, and nothing that reads a secret.
func publicBinding(binding []model.KeyValue) yaml.MapSlice {
	var out yaml.MapSlice
	for _, kv := range binding {
		if secretBindingName(kv.Key) || strings.Contains(kv.Value, "secret.") {
			continue
		}
		out = append(out, yaml.MapItem{Key: kv.Key, Value: kv.Value})
	}
	return out
}

// operation is the Arazzo view of an async version: where its operation is
// described and what a step for it can say.
func (op asyncOperation) operation() Operation {
	out := Operation{ID: op.id, Source: AsyncSource, Action: asyncAction(op.async), Reply: op.async.Action() == model.AsyncRequestReply}
	if rc := op.async.Receive; rc != nil {
		out.Timeout = rc.Timeout
		out.Match = rc.Match != ""
	}
	return out
}
